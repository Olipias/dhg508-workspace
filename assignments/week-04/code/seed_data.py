def year_of(schedule_original):
    """Extract the date wording and normalise it, keeping the original phrase."""
    import re
    m = re.search(r"((?:19|20)\d{2}(?:年\d{1,2}月)?)", schedule_original)
    if m:
        phrase = m.group(1)
        year = int(phrase[:4])
        return phrase, year, "从原文抽取「年+月」字样，取其四位年份为归一化年"
    if "长期" in schedule_original:
        return "（未注明）", "", "原文表述为长期做法，无确切起始年，故留空"
    return "（未注明）", "", "原文未给年份，留空"


def build_claims():
    rows = []
    for n, c in enumerate(COMPANIES, 1):
        cid, schedule_type = c[0], c[5]
        sched_orig, src, loc, note = c[7], c[8], c[9], c[10]
        phrase, year, rule = year_of(sched_orig)
        rows.append([
            f"CL{n:03d}", cid, schedule_type, sched_orig, phrase,
            year if year != "" else "", rule, c[6], src, loc, note,
        ])
    return rows


